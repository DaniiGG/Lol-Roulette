// Helper functions
export function getChampionRegions(championName: string): string[] {
  return CHAMPION_REGIONS[championName] || [];
}

export function getChampionClasses(championName: string): string[] {
  return CHAMPION_CLASSES[championName] || [];
}

export function championHasRegion(championName: string, region: string): boolean {
  const regions = getChampionRegions(championName);
  return regions.includes(region);
}

export function championHasClass(championName: string, className: string): boolean {
  const classes = getChampionClasses(championName);
  return classes.includes(className);
}